"""Apply root-approved editorial proposals; immutable revisions, no peer credit."""
from copy import deepcopy
from pathlib import Path
import difflib
import json
from rcwh.candidate_reviews import canonical_bytes
from rcwh.corpus.dataset import rebuild_scope
from rcwh.generation.records import binding, bound_bytes
from rcwh.generation.session import prepare_request, import_draft
from rcwh.generation.writing import feedback_report
from rcwh.workflow.attribution import release_attribution

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent

def write(relative, value):
    target = ROOT / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    raw = value if isinstance(value, bytes) else canonical_bytes(value)
    if target.exists():
        assert target.read_bytes() == raw, f'resume would replace retained bytes: {relative}'
    else:
        target.write_bytes(raw)
    return binding(ROOT, relative)

def run():
    design = json.loads((OUT / 'design-decisions.json').read_bytes())
    bound_bytes(ROOT, design['basis_request'])
    selection = json.loads((ROOT / 'data/agent_release/selection-81-100-v4.json').read_bytes())
    assert not (ROOT / 'data/agent_release/selection-81-100-v5.json').exists()
    # A new local contract and package is explicit; no existing frozen input is overwritten.
    design_ref = binding(ROOT, f'{OUT.relative_to(ROOT).as_posix()}/design-decisions.json')
    contract_refs = {}
    for sid in ('92-S6', '93-S2'):
        c = json.loads((ROOT / f'data/planning/contracts/agent-final-v1/{sid}.v2.json').read_bytes())
        c['revision'] = 'v3'
        disclosure = 'ROOT_V4_C_EDITORIAL_PLACEMENT: 原章卡把唯一正是二句置于92；本轮因实际离监及归家发生在93，将同一原句迁至93-S2吃热粥后、凤姐死亡前。不是原章卡已有此安排，不新增诗、不更改W93、世界入口或历史证据。'
        c['notes'] += ' ' + disclosure
        c['unresolved'].append(disclosure)
        if sid == '92-S6':
            b = next(b for b in c['required_beats'] if b['id'] == '92-S6-R2')
            b['description'] = '保留饭香、窄门及等待放行接口；唯一“正是”原二句与实际归巷、吃热饭的经验一同迁入93-S2，不在宝玉尚在监内时预支门外经历。“门里十日”不填精确羁押时长。'
            b['editorial_override'] = {'decision': design_ref, 'original_placement': '92章末，见原grounding；该grounding不证明93新位置', 'authority_effect': 'NONE'}
        else:
            c['required_beats'].append({'id': '93-S2-R4', 'description': '实际放行过门、到借院并先吃热粥后、凤姐死亡前，承接从92迁入的唯一原二句：“门里十日，只知饭冷灯昏；门外一程，才觉人间路窄。”不新增人物诗或作者韵文，不当作获释颂、全案结论或凤姐挽诗。', 'status': 'PENDING', 'scope': 'CURRENT_IMPLEMENTATION_REQUIREMENT_NOT_HISTORICAL_FACT', 'editorial_override': {'decision': design_ref, 'original_placement': '92-S6-R2及其原章卡grounding，未将原章卡伪称为93位置依据', 'authority_effect': 'NONE'}})
        contract_refs[sid] = write(f'data/planning/contracts/agent-final-v1/{sid}.v3.json', c)
    for row in selection['chapters']:
        ch = row['chapter']
        if ch not in (92, 93): continue
        previous = deepcopy(row)
        package = json.loads(bound_bytes(ROOT, row['writing_package']))
        v = 6 if ch == 92 else 5
        package['id'] = f'writing-package:ch{ch}:agent-research:v{v}'
        package['purpose'] += ' v4研究编辑：显式选择局部合同新版本，将原92末唯一二句迁入93实际归家热粥之后；原章卡不变，新落位为协调者C层编辑选择，非新增史料许可。'
        sid = '92-S6' if ch == 92 else '93-S2'
        package['plan'] = [contract_refs[sid] if b['path'].endswith(sid + '.v2.json') else b for b in package['plan']]
        row['writing_package'] = write(f'data/writing/packages/ch{ch}-agent-research-v{v}.json', package)
        base = f'data/agent_release/rebind-v6/ch{ch}'
        prepared = write(base + '-request.json', prepare_request(ROOT, package_path=row['writing_package']['path'], chapter=ch, renderer_version=2))
        result = import_draft(ROOT, row['candidate']['path'], prepared['path'], session_id=f'rebind-v6:ch{ch}', session_model_label='current agent environment (declared); custody only, body NOT generated by this new package')
        row.update(candidate=result['candidate'], draft=result['draft'])
        receipt = {'schema_version': 1, 'kind': 'REBIND_DISCLOSURE', 'chapter': ch, 'edition': 'rebind-v6', 'current': {k: row[k] for k in ('candidate','draft','writing_package')}, 'previous': {k: previous[k] for k in ('candidate','draft','writing_package')}, 'previous_rebind_receipt': previous['rebind_receipt'], 'prose_identical_to_previous': True, 'declaration': '正文未由本次v6重绑请求生成；这里只为新局部合同创建相同字节保管父稿，随后实际编辑另作有父稿的revision。原作者、实际编辑者和历次重绑保管链均保留。', 'authority_effect':'NONE','usage':'RESEARCH_ONLY'}
        row['rebind_receipt'] = write(f'data/agent_release/rebind-v6/receipts/ch{ch}.json', receipt)
        assert row['candidate'] == previous['candidate']
        write(base + '-result.json', {'import': result, 'attribution': release_attribution(ROOT,row)})
    texts = {}
    for row in selection['chapters']:
        text = bound_bytes(ROOT, row['candidate']).decode()
        for e in (e for e in design['edits'] if e['chapter'] == row['chapter']):
            assert text.count(e['before']) == 1, (row['chapter'], e['issue_id'])
            text = text.replace(e['before'], e['after'])
        texts[row['chapter']] = text
    summary = []
    for row in selection['chapters']:
        ch = row['chapter']
        if ch not in design['changed_chapters']:
            continue
        previous = deepcopy(row)
        old = bound_bytes(ROOT, row['candidate']).decode()
        new = texts[ch]
        base = f'{OUT.relative_to(ROOT).as_posix()}/revisions/ch{ch}'
        feedback = write(base + '-feedback.json', feedback_report(ROOT, row['draft']['path']))
        choices = [d for d in design['decisions'] if any(e['chapter'] == ch and e['issue_id'] == d['issue_id'] for e in design['edits'])]
        notes = {'kind': 'ROOT_ACTUAL_EDITORIAL_REVISION', 'chapter': ch,
                 'declaration': '根协调者核对、设计并实际应用；本轮没有设计协作者。不是由新写作提示词从头生成；不把设计建议记为同行意见。原作者、父稿及纯重绑保管链保留。',
                 'editor': f'session:coordinator-edit-20261026:ch{ch}',
                 'root_choices': choices,
                 'edits': [e for e in design['edits'] if e['chapter'] == ch],
                 'authority_effect': 'NONE', 'usage': 'RESEARCH_ONLY'}
        note_ref = write(base + '-editorial-notes.json', notes)
        prepared = prepare_request(ROOT, parent_path=row['draft']['path'], feedback_path=feedback['path'],
                                   notes_path=note_ref['path'], revision_template='revise-v2', renderer_version=2)
        request = write(base + '-request.json', prepared)
        text = write(base + '-edited.txt', new.encode())
        result = import_draft(ROOT, text['path'], request['path'], session_id=f'coordinator-edit-20261026:ch{ch}',
                              session_model_label='current agent environment (declared); root actual editor, no design delegation',
                              parent_path=row['draft']['path'], feedback_path=feedback['path'])
        row.update(candidate=result['candidate'], draft=result['draft'])
        attribution = release_attribution(ROOT, row)
        assert attribution['contributors'][-1]['principal_id'] == f'session:coordinator-edit-20261026:ch{ch}'
        record = {'chapter': ch, 'previous': previous, 'current': deepcopy(row), 'import': result,
                  'editorial_notes': note_ref, 'diff': '\n'.join(difflib.unified_diff(old.splitlines(), new.splitlines(), fromfile='v3', tofile='v4', lineterm='')),
                  'attribution': attribution, 'peer_review': 'PENDING_NEW_CONTEXT'}
        write(base + '-result.json', record)
        summary.append(record)
        print(f'ch{ch}: imported actual revision', flush=True)
    selection['id'] = 'selection:81-100:v5'
    write('data/agent_release/selection-81-100-v5.json', selection)
    write(f'{OUT.relative_to(ROOT).as_posix()}/revisions/summary.json', summary)
    print(json.dumps({'status': 'PASS', 'revised': design['changed_chapters'], 'review': 'PENDING'}, ensure_ascii=False))

if __name__ == '__main__':
    with rebuild_scope():
        run()
